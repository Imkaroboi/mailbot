import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const temp = await mkdtemp(join(tmpdir(), 'mailbot-trash-')); 
const outfile = join(temp, 'trash.mjs');
await build({ entryPoints: ['lib/google-mail.ts'], bundle: true, platform: 'node', format: 'esm', outfile });
const { trashGoogleMail } = await import(outfile);
const session = { token: 'mock', expiresAt: Date.now() + 3600_000, email: 'me@example.com' };
const ids = Array.from({ length: 21_000 }, (_, i) => (i + 1).toString(16));
const headers = ids.map(id => ({ id, sender: 'news@example.com' }));
const originalNow = Date.now;
let clock = originalNow();
Date.now = () => clock += 1_000; // Skip quota waits; this is a functional test, not a speed benchmark.
let writes = []; let reads = 0; let getCalls = 0;
let liveIds = [...ids, 'ffffff'];
let controller; let failPage = false; let failWrite = false; let cancelDuringWrite = false;
let completedWrites = 0; let activeWrites = 0; let maximumActiveWrites = 0;
globalThis.fetch = async (input, init = {}) => {
  const url = new URL(input);
  assert.ok(!url.pathname.includes('batchDelete'), 'must never permanently delete mail');
  if (url.pathname.endsWith('/messages/batchModify')) {
    assert.equal(init.method, 'POST');
    const body = JSON.parse(init.body);
    assert.deepEqual(body.addLabelIds, ['TRASH']);
    assert.deepEqual(body.removeLabelIds, ['INBOX']);
    assert.ok(body.ids.length <= 1000);
    assert.ok(body.ids.every(id => ids.includes(id)), 'new/unreviewed mail cannot enter a write');
    assert.equal(init.signal, undefined, 'in-flight writes must finish when Cancel is pressed');
    writes.push(body.ids);
    activeWrites++; maximumActiveWrites = Math.max(maximumActiveWrites, activeWrites);
    if (cancelDuringWrite === true || cancelDuringWrite === writes.length) controller.abort();
    const failThisWrite = failWrite === true || failWrite === 'first' && body.ids.includes('1');
    await new Promise(resolve => setTimeout(resolve, 20));
    activeWrites--; completedWrites++;
    return failThisWrite ? new Response(JSON.stringify({ error: { message: 'Unavailable' } }), { status: 503 }) : new Response(null, { status: 200 });
  }
  if (url.pathname.endsWith('/messages')) {
    reads++;
    const q = url.searchParams.get('q');
    assert.ok(q.includes('-in:sent -in:drafts -in:trash'));
    if (!q.startsWith('from:(')) assert.ok(q.includes('-is:starred -label:IMPORTANT'), 'general cleanup must recheck protected labels');
    assert.equal(url.searchParams.get('includeSpamTrash'), 'true');
    if (failPage) return new Response(JSON.stringify({ error: { message: 'Unavailable' } }), { status: 503 });
    const offset = Number(url.searchParams.get('pageToken')) || 0;
    const partition = q.includes('-in:inbox') ? liveIds.filter(id => parseInt(id, 16) % 2) : liveIds.filter(id => !(parseInt(id, 16) % 2));
    const messages = partition.slice(offset, offset + 500).map(id => ({ id }));
    return Response.json({ messages, ...(offset + 500 < partition.length ? { nextPageToken: String(offset + 500) } : {}) });
  }
  getCalls++;
  return Response.json({ id: url.pathname.split('/').at(-1), payload: { headers: [{ name: 'From', value: 'other@example.com' }] } });
};
try {
  const stages = [];
  const result = await trashGoogleMail(session, [...ids, ids[0]], 'news@example.com', (_n, state) => stages.push(state.phase), undefined, headers);
  assert.equal(result.moved.length, 21_000);
  assert.equal(writes.length, 21);
  assert.equal(reads, 42);
  assert.equal(getCalls, 0, 'reviewed immutable headers eliminate per-message reads');
  assert.ok(maximumActiveWrites > 1 && maximumActiveWrites <= 3, 'bulk requests overlap with bounded concurrency');
  assert.equal(stages[0], 'checking'); assert.equal(stages.at(-1), 'moving');
  assert.deepEqual(result.remaining, []);
  writes = []; completedWrites = 0; controller = new AbortController(); cancelDuringWrite = true;
  const canceled = await trashGoogleMail(session, ids.slice(0, 2100), 'news@example.com', undefined, controller.signal, headers);
  assert.equal(canceled.cancelled, true);
  assert.equal(writes.length, 1);
  assert.equal(completedWrites, 1);
  assert.equal(canceled.moved.length, 1000);
  assert.equal(canceled.undo.length, canceled.moved.length, 'emails moved before Cancel must remain undoable');
  assert.equal(canceled.remaining.length, 1100);
  writes = []; completedWrites = 0; controller = new AbortController(); cancelDuringWrite = 3;
  const lateCancel = await trashGoogleMail(session, ids.slice(0, 5000), 'news@example.com', undefined, controller.signal, headers);
  assert.equal(writes.length, 3); assert.equal(completedWrites, 3);
  assert.equal(lateCancel.moved.length, 3000); assert.equal(lateCancel.remaining.length, 2000);
  assert.ok(lateCancel.cancelled && !lateCancel.failed.length);
  cancelDuringWrite = false; writes = []; liveIds = ids.slice(0, 10).filter(id => id !== '3');
  const protectedMail = await trashGoogleMail(session, ids.slice(0, 10));
  assert.equal(protectedMail.moved.length, 9);
  assert.deepEqual(protectedMail.remaining, ['3'], 'ineligible mail remains unmodified');
  writes = []; failPage = true;
  const failedRead = await trashGoogleMail(session, ids.slice(0, 10), 'news@example.com', undefined, undefined, headers);
  assert.equal(writes.length, 0, 'no writes until the eligibility check finishes');
  assert.equal(failedRead.failed.length, 10);
  failPage = false; liveIds = ids.slice(0, 5000); failWrite = true;
  const failedBatch = await trashGoogleMail(session, ids.slice(0, 5000), 'news@example.com', undefined, undefined, headers);
  assert.ok(writes.length >= 1 && writes.length <= 3, 'failed group stops queued writes while accounting for groups already sent');
  assert.equal(failedBatch.moved.length, 0);
  assert.equal(failedBatch.failed.length, writes.length * 1000);
  writes = []; failWrite = 'first';
  const partialFailure = await trashGoogleMail(session, ids.slice(0, 5000), 'news@example.com', undefined, undefined, headers);
  assert.equal(writes.length, 3); assert.equal(partialFailure.failed.length, 1000);
  assert.equal(partialFailure.moved.length, 2000, 'successful in-flight groups must still be counted after another group fails');
  assert.equal(partialFailure.undo.length, partialFailure.moved.length);
  assert.equal(partialFailure.error, 'Unavailable');
  failWrite = false; writes = [];
  const wrongSender = await trashGoogleMail(session, ['1'], 'news@example.com', undefined, undefined, [{ id: '1', sender: 'other@example.com' }]);
  assert.equal(writes.length, 0); assert.deepEqual(wrongSender.failed, ['1']);
  const uncached = await trashGoogleMail(session, ['1'], 'news@example.com');
  assert.equal(writes.length, 0); assert.deepEqual(uncached.failed, ['1']);
  controller = new AbortController(); controller.abort();
  const beforeStart = await trashGoogleMail(session, ['1'], 'news@example.com', undefined, controller.signal, headers);
  assert.equal(beforeStart.cancelled, true); assert.equal(writes.length, 0);
  console.log('21,000 reviewed messages: 42 label checks + 21 bulk Trash writes; protected/new mail, empty responses, failures, and cancellation passed.');
} finally { Date.now = originalNow; await rm(temp, { recursive: true, force: true }); }
